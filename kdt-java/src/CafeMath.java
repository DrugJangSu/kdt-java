public class CafeMath {
    public static void main(String[] args) {
        int won = 10000;
        int people = 3;
        int each = won / people; // 3333, 몫만
        int left = won % people; // 1, 나머지
        System.out.println("each=" + each);
        System.out.println("left=" + left);

//        Integer.MAX_VALUE;
//        final double PI = 3.14;
//        PI = 3.12;
    }
}
